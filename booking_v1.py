# ระบบจองห้อง - เวอร์ชัน 1 (ขั้นเริ่มต้น)
# - เก็บข้อมูลใน list ธรรมดา
# - จองได้ครั้งเดียวแล้วจบโปรแกรม
# - ยังไม่มีการตรวจสอบข้อมูล ยังไม่มียกเลิก ยังไม่มีบันทึกไฟล์

rooms = ["101", "102", "103", "104", "105"]
booked = []

print("=== ระบบจองห้อง v1 ===")
print("ห้องทั้งหมด:", rooms)

name = input("ชื่อผู้จอง: ")
room = input("เลือกห้อง: ")

if room in rooms:
    booked.append([room, name])
    print("จองสำเร็จ! ห้อง", room, "โดย", name)
else:
    print("ไม่มีห้องนี้")

print("รายการจอง:", booked)
